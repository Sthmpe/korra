  // ✅ THE HELPER: Flattens the groups into one long list for the search bar
  static List<String> get flatList {
    return groupedCategories
        .expand((group) => (group['categories'] as List<dynamic>).cast<String>())
        .toList();
  }

  // ✅ NEW: Smart Search Helper (Searches both Groups and Items)
  static List<String> searchCategories(String query) {
    // 1. Remove excess whitespace from the beginning and end
    final cleanQuery = query.trim(); 
    
    if (cleanQuery.isEmpty) return flatList;

    final lowerQuery = cleanQuery.toLowerCase();
    List<String> results = [];

    for (var groupMap in groupedCategories) {
      final groupName = (groupMap['group'] as String).toLowerCase();
      final categories = (groupMap['categories'] as List<dynamic>).cast<String>();

      // Condition 1: Group name match (e.g., they typed "fashion" or "tech")
      if (groupName.contains(lowerQuery)) {
        results.addAll(categories);
      } 
      // Condition 2: Item name match
      else {
        final matchingItems = categories.where((cat) => cat.toLowerCase().contains(lowerQuery));
        results.addAll(matchingItems);
      }
    }

    return results;
  }
